#!/usr/bin/env python3
"""Регрессионная проверка RFC страницы «Стандарты» (issue #420).

Постановка #420 просит аналитику и RFC на правку страницы «Стандарты», но
запрещает менять сайт в рамках задачи. Проверка фиксирует контракт
постановки, а не качество текста:

* RFC в статусе ``proposed``, анализ в статусе knowledge-словаря; frontmatter
  обоих проходит валидатор Хаба; RFC начинается с «Кратко для руководителя»;
* решения DEC-420-01…12 заякорены в RFC и зарегистрированы в
  ``docs/rfc/rfc-register.md``; открытые вопросы Q1–Q7 на месте;
* ответы на пункты постановки: основания глоссария с заглушкой D0,
  введение со структурой, единый шаблон карточки, «необходимо /
  достаточно», 5±2 с данными прогонов, вердикт готовности;
* прототип (``build.py --check``) и итоги фокус-группы (``score.py --check``)
  актуальны; приложение RFC — ровно то, что видел финальный раунд;
* цель по идентификации (≥ 85 %) достигнута в последнем раунде, а если цель
  по удовлетворённости (≥ 95 %) не достигнута, RFC и анализ это говорят;
  цифры в RFC совпадают с ``results.md``;
* относительные ссылки и якоря RFC, анализа и персон разрешаются;
* ``site/`` этим PR не меняется (сравнение с общей базой ``main``, когда
  история доступна).
"""

import re
import subprocess
import sys
import unittest
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RFC = ROOT / "docs/rfc/2026-10-standards-page-rfc.md"
ANALYSIS = ROOT / "docs/analysis/2026-10-31-standards-page-review.md"
RFC_REGISTER = ROOT / "docs/rfc/rfc-register.md"
CHANGELOG = ROOT / "CHANGELOG.md"
EXP = ROOT / "experiments/issue_420"
FOCUS = EXP / "focus-group"
RESULTS = FOCUS / "results.md"
PROPOSAL_PAGE = EXP / "prototype/proposal-page.md"
PERSONAS = FOCUS / "personas.md"

DECISIONS = [f"DEC-420-{n:02d}" for n in range(1, 13)]
QUESTIONS = [f"Q{n}" for n in range(1, 8)]
TARGET_ID, TARGET_SAT = 85, 95
CARD_BLOCKS = ("Стадия · гейт · адресат", "Что", "Зачем", "Состав", "Как пишем",
               "Правило раздела", "Принимаем, когда", "Метрики", "Понятия, пример, основание")
APPENDIX_BEGIN = "<!-- BEGIN issue-420 proposal-page: generated by experiments/issue_420/prototype/build.py -->"
APPENDIX_END = "<!-- END issue-420 proposal-page -->"

LINK = re.compile(r"\]\(([^\s)]+)\)")


def text(path):
    return path.read_text(encoding="utf-8")


def slug(heading):
    heading = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", heading).strip().lower()
    return re.sub(r"[^\w\- ]", "", heading).replace(" ", "-")


def anchors(path):
    found, seen, fenced = set(), Counter(), False
    for line in text(path).splitlines():
        if line.startswith("```"):
            fenced = not fenced
            continue
        found.update(re.findall(r'<a id="([^"]+)"', line))
        match = None if fenced else re.match(r"^#{1,6}\s+(.*?)\s*#*\s*$", line)
        if match:
            base = slug(match.group(1))
            found.add(base if not seen[base] else f"{base}-{seen[base]}")
            seen[base] += 1
    return found


def frontmatter(markdown):
    if not markdown.startswith("---\n"):
        return {}
    block = markdown[4:markdown.index("\n---\n", 4)]
    fields = {}
    for line in block.splitlines():
        if ":" in line and not line.startswith((" ", "-")):
            key, value = line.split(":", 1)
            fields[key.strip()] = value.strip().strip('"')
    return fields


def section(markdown, heading):
    """Текст раздела от заголовка до следующего заголовка того же уровня."""
    level = heading.split(" ", 1)[0]
    start = markdown.index(heading + "\n")
    rest = markdown[start + len(heading):]
    match = re.search(rf"^{level} ", rest, re.M)
    return rest[: match.start()] if match else rest


def table_rows(markdown, header):
    lines = markdown.split(header, 1)[1].splitlines()[2:]
    rows = []
    for line in lines:
        if not line.startswith("|"):
            break
        rows.append([cell.strip() for cell in line.strip().strip("|").split("|")])
    return rows


def rounds():
    """Итоги из results.md: {(раунд, вариант): (идентификация %, удовлетворены %)}."""
    header = "| Раунд | Вариант | Персон | Идентификация | Удовлетворены |"
    rows = table_rows(text(RESULTS), header)
    return [(row[0], row[1], int(row[3].rstrip(" %")), int(row[4].rstrip(" %"))) for row in rows]


def broken_links(path):
    missing = []
    for target in LINK.findall(text(path)):
        if target.startswith(("http://", "https://", "mailto:")):
            continue
        rel, _, frag = target.partition("#")
        resolved = (path.parent / rel).resolve() if rel else path
        if not resolved.exists():
            missing.append(target)
        elif frag and resolved.suffix == ".md" and frag not in anchors(resolved):
            missing.append(target)
    return missing


def run(*args):
    return subprocess.run(list(args), cwd=ROOT, capture_output=True, text=True)


class StandardsPageRfcTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.md = text(RFC)
        cls.fm = frontmatter(cls.md)
        cls.analysis = text(ANALYSIS)
        cls.afm = frontmatter(cls.analysis)

    def test_rfc_frontmatter(self):
        self.assertEqual(self.fm.get("status"), "proposed")
        self.assertEqual(self.fm.get("owner"), "G-Ivan-A")
        self.assertEqual(self.fm.get("type"), "rfc")
        self.assertIn("issues/420", self.fm.get("source", ""))
        for issue in ("395", "413", "417", "418"):
            self.assertIn(f"issues/{issue}", self.fm.get("related_issues", ""))
        self.assertNotIn("ai-generated", self.fm)

    def test_analysis_frontmatter(self):
        self.assertIn(self.afm.get("status"), {"draft", "reviewed", "canonical"})
        self.assertEqual(self.afm.get("analysis-subtype"), "recommendation")
        self.assertIn("issues/420", self.afm.get("source", ""))
        self.assertRegex(self.afm.get("based_on", ""), r"/tree/[0-9a-f]{40}$")
        self.assertNotIn("ai-generated", self.afm)

    def test_frontmatter_validator(self):
        for path in (RFC, ANALYSIS):
            with self.subTest(path=path.name):
                proc = run("./tools/validate-frontmatter.sh", str(path))
                self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

    def test_executive_summary_first(self):
        body = self.md.split("\n---\n", 1)[1]
        headings = re.findall(r"^## (.+)$", body, re.M)
        self.assertEqual(headings[:2], ["Кратко для руководителя", "Как читать"])

    def test_analysis_minimum_sections(self):
        headings = re.findall(r"^## (.+)$", self.analysis, re.M)
        self.assertEqual(headings[0], "BLUF")
        for needed in ("Контекст и охват", "Рекомендации", "Related Artifacts",
                       "Фокус-группа", "5±2: критика и данные прогонов",
                       "Вердикт: готовность для руководителей", "Матрица согласованности"):
            self.assertIn(needed, headings)

    def test_decisions_anchored_and_registered(self):
        register = text(RFC_REGISTER)
        own = anchors(RFC)
        for dec in DECISIONS:
            with self.subTest(decision=dec):
                anchor = dec.lower()
                self.assertIn(anchor, own)
                self.assertIn(f"| [RFC-420-DEC-{dec[-2:]}](2026-10-standards-page-rfc.md#{anchor}) |",
                              register)
        head = register.split("\n---\n", 1)[0]
        self.assertIn('"docs/rfc/2026-10-standards-page-rfc.md"', head)
        self.assertIn("issues/420", head)

    def test_open_questions(self):
        rows = table_rows(section(self.md, "## Open Questions"), "| № | Вопрос | Кто отвечает |")
        self.assertEqual([row[0] for row in rows], QUESTIONS)

    def test_issue_points_answered(self):
        answers = section(self.md, "## 1. Ответы на постановку")
        for needle in ("Основания глоссария", "Справочника согласованных терминов Манго нет",
                       "«Общий»", "Меню справа", "Согласованность", "2.1 и 2.2",
                       "5±2", "Готовность для руководителей"):
            self.assertIn(needle, answers)
        self.assertIn("меню **слева**", answers)

    def test_glossary_bases_with_d0_stub(self):
        rows = table_rows(section(self.md, "## 3. Основания глоссария"),
                          "| Приоритет | Основание | Роль | Статус |")
        self.assertEqual([row[0] for row in rows], ["1", "2", "3", "4", "5", "6"])
        self.assertIn("D0", rows[1][1])
        self.assertIn("заглушка", rows[1][3])
        self.assertIn("кандидат в D0", self.md)
        self.assertIn("С0–С4", self.md)

    def test_card_template(self):
        rows = table_rows(section(self.md, "## 2. Единый шаблон карточки"),
                          "| № | Блок | Содержание | Кому |")
        self.assertEqual(tuple(row[1] for row in rows), CARD_BLOCKS)
        self.assertIn("§5.2.5", self.md)
        self.assertIn("§5.2.6", self.md)

    def test_five_plus_minus_two_backed_by_runs(self):
        part = section(self.analysis, "## 5±2: критика и данные прогонов")
        table = text(EXP / "fr-levels.md").strip()
        self.assertIn(table, part, "таблица прогонов в анализе устарела: count_fr_levels.py")
        proc = run(sys.executable, "experiments/issue_420/count_fr_levels.py")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertEqual(proc.stdout.strip(), table)
        for name in ("Miller", "Cowan"):
            self.assertIn(name, part)

    def test_prototype_and_results_fresh(self):
        for script in ("experiments/issue_420/prototype/build.py",
                       "experiments/issue_420/focus-group/score.py"):
            with self.subTest(script=script):
                proc = run(sys.executable, script, "--check")
                self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

    def test_appendix_is_what_final_round_saw(self):
        self.assertIn(APPENDIX_BEGIN, self.md)
        self.assertIn(APPENDIX_END, self.md)
        latest = sorted(FOCUS.glob("round-*"), key=lambda p: int(p.name.split("-")[1]))[-1]
        stimuli = [p for p in (latest / "stimuli").glob("stimulus-*.md")
                   if text(p) == text(PROPOSAL_PAGE)]
        self.assertTrue(stimuli, f"{latest.name}: стимул не совпадает с proposal-page.md")

    def test_targets_reported_honestly(self):
        data = rounds()
        _, _, ident, sat = data[-1]
        self.assertGreaterEqual(ident, TARGET_ID)
        summary = section(self.md, "## Кратко для руководителя")
        focus = section(self.analysis, "## Фокус-группа")
        if sat < TARGET_SAT:
            self.assertIn("удовлетворённости (95 %) **не", summary)
            self.assertIn("**не достигнута**", section(self.md, "## Фокус-группа и что она не закрыла"))
            self.assertIn("Что не достигнуто", focus)
        baseline = [row for row in data if row[1] == "baseline"][0]
        rfc_rows = table_rows(self.md, "| Вариант | Идентификация | Удовлетворены (оценка ≥ 4) |")
        self.assertIn(f"{baseline[2]} %", rfc_rows[0][1])
        self.assertIn(f"| {ident} % | {sat} % |", "| " + " | ".join(rfc_rows[-1][1:3]) + " |")
        analysis_rows = table_rows(focus, "| Раунд | Вариант | Идентификация | Удовлетворены |")
        self.assertEqual([(r[2], r[3]) for r in analysis_rows],
                         [(f"{i} %", f"{s} %") for _, _, i, s in data])

    def test_links_resolve(self):
        for path in (RFC, ANALYSIS, PERSONAS):
            with self.subTest(path=path.name):
                self.assertEqual(broken_links(path), [])

    def test_site_unchanged_by_this_pr(self):
        base = None
        for ref in ("upstream/main", "origin/main", "main"):
            proc = run("git", "merge-base", "HEAD", ref)
            if proc.returncode == 0:
                base = proc.stdout.strip()
                break
        if base is None:
            self.skipTest("история main недоступна (поверхностный checkout)")
        proc = run("git", "diff", "--name-only", base, "--", "site/")
        self.assertEqual(proc.stdout.strip(), "", "постановка #420 запрещает менять сайт")

    def test_changelog(self):
        self.assertIn("Issue #420", text(CHANGELOG).split("\n## ", 2)[1])


if __name__ == "__main__":
    unittest.main(verbosity=1 if "-q" in sys.argv else 2, argv=[sys.argv[0]])
