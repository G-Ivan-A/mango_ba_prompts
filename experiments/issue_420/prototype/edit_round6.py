"""Round-6 edits to content.json (issue #420): answers round-5 focus-group remarks
(customer block without codes, one rule per card, section list in the summary).
Kept for traceability; run once: python3 experiments/issue_420/prototype/edit_round6.py"""
import json, pathlib
p = pathlib.Path(__file__).with_name("content.json")
c = json.loads(p.read_text())
top = next(v for v in c.values() if isinstance(v, dict) and "summary" in v)
top["summary"][0][1] = ("Документ требований к доработке продукта Манго. Пишет бизнес-аналитик (БА), чтобы Заказчик, БА и разработка одинаково понимали, что делаем, зачем и как принять результат. "
    "8 разделов: термины, бизнес-контекст, требования к функциям, требования к качеству, описание решения, ограничения, сценарии проверки, риски и план приёмки.")
top["customer"] = [
    ["Кто вы", "Заказчик — тот, кто запросил доработку и подписывает требования: клиент Манго или подразделение компании, от имени которого пришёл запрос. Вы отвечаете на вопросы и подписываете требования; решение и оценку готовит Манго."],
    ["1. Вопросы", "В начале работы БА может прислать вопросы. Ответ нужен, чтобы требования не строились на догадках."],
    ["2. Подпись требований («Согласование 1»)", "Вы читаете разделы 1–4 — термины, контекст, требования к функциям и к качеству — и предварительную оценку «от». Подписывая, вы подтверждаете: задача понята верно, список требований полон."],
    ["3. Утверждение решения", "Когда решение готово и его приняли владелец продукта, архитектор и руководитель КК, вы получаете описание решения для вас, ограничения, план приёмки и итоговую оценку. Утверждаете их или возвращаете на уточнение."],
    ["4. Приёмка", "Результат принимают по критериям плана приёмки; каждый критерий ведёт к подписанному вами требованию."],
    ["Если что-то изменилось", "На любом шаге документ можно вернуть на уточнение. БА возвращается к тому этапу, где причина, и записывает возврат в журнал решений."],
    ["Сколько времени", "Вы участвуете в трёх точках: вопросы, подпись требований, утверждение решения. Срок ответа в каждой точке БА согласует с вами при запуске задачи; этот стандарт сроков не задаёт."],
]
for card in c["cards"]:
    if card["n"] == "1":
        card["special"]["lead"] = ("Термин Заказчика сохраняется дословно. Дальше порядок оснований постоянный: термин берётся из первого источника списка, где он есть, "
            "а нижние источники не заменяют верхние молча. Поэтому термин из D0 всегда побеждает глоссарий продукта и словари.")
        for x in card["composition"]:
            if x["title"].startswith("Расхождение"):
                x["text"] = ("блок после таблицы — только если найдены расхождения С1–С3: рекомендация с классом расхождения; "
                    "менять ли термин, решает БА и записывает решение в журнал 8.5.")
    if card["n"] == "3":
        card["special"]["lead"] = ("На каждом уровне списка — 3–7 пунктов: 3–7 пунктов 3.N и 3–7 ФТ в группе 3.N.M. "
            "Больше 7 — сгруппировать по бизнес-возможности; если групп всё ещё больше 7 — БА решает, не разбить ли задачу. "
            "Отклонение от 3–7 допустимо только с обоснованием в 8.5; требования ради числа не придумывают. Правило действует только в разделе 3.")
    if card["n"] == "6":
        card["special"]["lead"] = ("2.4.2 — что доработка не делает, включая неподдерживаемые платформы и версии («не поддерживается КЦ Десктоп»). "
            "6.2 — прочие внешние условия, которые сужают то, что она делает (лимит запросов CRM). "
            "6.1 — не решение, а его следствия из раздела 5, которые заметит Заказчик (задержка, порядок, поведение при ошибке). "
            "Переходное правило для документов, начатых до этого правила, — в стандарте раздела 6.")
p.write_text(json.dumps(c, ensure_ascii=False, indent=2) + "\n")
print("ok")
