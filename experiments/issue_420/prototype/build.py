# --------------------------------------------------------------------------- RFC appendix


def rfc_with_appendix(rfc_text: str, markdown: str) -> str:
    if BEGIN not in rfc_text or END not in rfc_text:
        raise SystemExit(f"{RFC}: markers not found")
    head, rest = rfc_text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    # Demote headings by two levels so the appendix nests under "## Приложение".
    body = "\n".join(("##" + line) if line.startswith("#") else line for line in markdown.splitlines())
    return f"{head}{BEGIN}\n\n{body}\n\n{END}{tail}"


def main() -> int:
    data = load()
    markdown = render_markdown(data)
    outputs = {HTML_OUT: render_html(data), MD_OUT: markdown}
    if RFC.exists():
        outputs[RFC] = rfc_with_appendix(RFC.read_text(encoding="utf-8"), markdown)
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if "--check" in sys.argv:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for p in stale:
        p.write_text(outputs[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
