#!/usr/bin/env python3
"""Build the site-v2 prototype for issue #420 (RFC v0.2).

The live site in site/ is NOT changed (issue #420: «не меняем страницы сайта»).
The script copies site/ into experiments/issue_420/site-v2/out/ (gitignored)
and applies the recommended content from content.py:

- menu: О проекте · Каталог · Стандарты · Процессы · Дашборд · Справочник;
- new pages «О проекте» (#about) and «Справочник» (#glossary, #glossary?term=<id>);
- Standards page: H1, Введение (structure only), 8 cards by one template;
- Processes: two collapsible streams; Dashboard: numbers only;
- data label fix «Описание решения» → «Описание разрабатываемого решения».

It also writes pages.md (Markdown copy of the recommended content) and the
RFC appendix between the BEGIN/END markers.

Usage:
    python3 experiments/issue_420/site-v2/build.py           # build out/, write pages.md and the RFC appendix
    python3 experiments/issue_420/site-v2/build.py --check   # verify pages.md and the RFC appendix are current
"""

from __future__ import annotations

import html
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))

import content as C  # noqa: E402

SITE = ROOT / "site"
OUT = HERE / "out"
PAGES_MD = HERE / "pages.md"
RFC = ROOT / "docs" / "rfc" / "2026-10-standards-page-rfc.md"
BEGIN = "<!-- BEGIN issue-420 site-v2: generated by experiments/issue_420/site-v2/build.py -->"
END = "<!-- END issue-420 site-v2 -->"

TERM_RE = re.compile(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]")
BOLD_RE = re.compile(r"\*\*(.+?)\*\*")


def term_id(key: str) -> str:
    if key in C.TERM_IDS:
        return key
    if key in C.TERM_BY_LABEL:
        return C.TERM_BY_LABEL[key]
    raise KeyError(f"unknown glossary term: {key}")


# ------------------------------------------------------------------ inline
def h(text: str) -> str:
    """Inline markup → HTML."""
    out = []
    pos = 0
    for m in TERM_RE.finditer(text):
        out.append(BOLD_RE.sub(r"<strong>\1</strong>", html.escape(text[pos:m.start()], quote=False)))
        key, label = m.group(1), m.group(2) or m.group(1)
        tid = term_id(key)
        out.append(
            f'<a class="v2-term" href="#glossary?term={tid}" title="Справочник: {html.escape(key)}">'
            f"{html.escape(label, quote=False)}</a>"
        )
        pos = m.end()
    out.append(BOLD_RE.sub(r"<strong>\1</strong>", html.escape(text[pos:], quote=False)))
    return "".join(out)


def md(text: str) -> str:
    """Inline markup → Markdown (terms as plain text: the Справочник follows below)."""
    for m in TERM_RE.finditer(text):
        term_id(m.group(1))  # validate
    return TERM_RE.sub(lambda m: m.group(2) or m.group(1), text)


def ext(label: str, url: str) -> str:
    return f'<a href="{html.escape(url)}" target="_blank" rel="noreferrer">{html.escape(label)}</a>'


# ------------------------------------------------------------------ HTML pages
def nav_html() -> str:
    links = "\n".join(
        f'        <a href="#{page}" data-nav="{page}">{html.escape(label)}</a>' for page, label in C.NAV
    )
    return links


def about_html() -> str:
    a = C.ABOUT
    vision = "".join(f"<div><dt>{html.escape(k)}</dt><dd>{h(v)}</dd></div>" for k, v in a["vision"])
    principles = "".join(f"<li>{h(p)}</li>" for p in a["principles"])
    stages = "".join(
        f'<li data-status="{"current" if st == "сейчас" else "planned"}"><span class="v2-stage-num">{n}</span>'
        f"<div><strong>{html.escape(t)}</strong><p>{h(d)}</p></div><span class=\"status-pill\">{st}</span></li>"
        for n, t, d, st in a["stages"]
    )
    zones = "".join(
        f'<li><a href="#{page}">{html.escape(name)}</a> — {h(text)}</li>' for name, page, text in a["zones"]
    )
    meta_links = " · ".join(ext(label, url) for label, url in a["meta_links"])
    docs = " · ".join(ext(label, url) for label, url in a["docs"])
    return f"""
      <section class="page-band v2-about" id="about" data-page="about" aria-labelledby="about-title" hidden>
        <div class="section-head"><div><h1 id="about-title">{html.escape(a["title"])}</h1></div></div>
        <p class="v2-lead">{h(a["lead"])}</p>
        <div class="v2-about-grid">
          <article class="v2-panel"><h2>Видение</h2><dl class="v2-dl">{vision}</dl></article>
          <article class="v2-panel"><h2>Принципы</h2><ul class="v2-list">{principles}</ul>
            <h2>Мета-модель бизнес-анализа</h2><p>{h(a["meta_model"])}</p><p class="v2-links">{meta_links}</p></article>
        </div>
        <article class="v2-panel"><h2>Этапы автоматизации</h2><ol class="v2-stages">{stages}</ol></article>
        <article class="v2-panel"><h2>Разделы сайта</h2><ul class="v2-list">{zones}</ul>
          <p class="v2-links">Документы проекта: {docs}</p></article>
      </section>
"""


def glossary_html() -> str:
    groups = []
    for gid, gtitle in C.GLOSSARY_GROUPS:
        rows = "".join(
            f'<div class="v2-term-row" id="term-{tid}" tabindex="-1"><dt><strong>{html.escape(label)}</strong>'
            f"<span>{html.escape(full)}</span></dt><dd>{h(definition)}"
            f' <span class="v2-term-source">Источник: {ext(slabel, surl)}</span></dd></div>'
            for tid, label, full, definition, slabel, surl, group in C.GLOSSARY
            if group == gid
        )
        groups.append(f'<h2>{html.escape(gtitle)}</h2><dl class="v2-glossary">{rows}</dl>')
    return f"""
      <section class="page-band v2-glossary-band" id="glossary" data-page="glossary" aria-labelledby="glossary-title" hidden>
        <div class="section-head"><div><h1 id="glossary-title">Справочник</h1></div></div>
        {"".join(groups)}
      </section>
"""


def intro_html() -> str:
    items = []
    for n, title, comment, subs in C.INTRO:
        sub_html = ""
        if subs:
            sub_html = "<ol class=\"v2-intro-sub\">" + "".join(
                f"<li><span>{html.escape(sn)}</span> {h(st)}" + (f" — <em>{h(sc)}</em>" if sc else "") + "</li>"
                for sn, st, sc in subs
            ) + "</ol>"
        items.append(
            f'<li><a href="#standards?section={n}" data-standard-target="{n}"><span>{n}</span> {html.escape(md(title), quote=False)}</a>'
            f" — <em>{h(comment)}</em>{sub_html}</li>"
        )
    return (
        f'<section class="v2-intro" id="standard-intro" aria-labelledby="standard-intro-title">'
        f'<h2 id="standard-intro-title">{html.escape(C.INTRO_TITLE)}</h2><ol class="v2-intro-list">{"".join(items)}</ol></section>'
    )


def card_html(card: dict) -> str:
    n = card["n"]
    comp = "".join(f"<div><dt>{h(k)}</dt><dd>{h(v)}</dd></div>" for k, v in card["composition"])
    how = "".join(f"<li>{h(x)}</li>" for x in card["how"])
    crit = "".join(f"<tr><th scope=\"row\">{h(k)}</th><td>{h(v)}</td></tr>" for k, v in card["criteria"])
    metrics = "".join(f"<li><span>{h(k)}</span><strong>{h(v)}</strong></li>" for k, v in card["metrics"])
    ex_title, ex_body = card["example"]
    sources = " · ".join(ext(label, url) for label, url in card["sources"])
    return f"""
            <article class="standard-card v2-card" id="standard-{n}" data-bcreq-section="{n}" tabindex="-1" aria-labelledby="standard-title-{n}">
              <div class="standard-heading"><span class="standard-number">{int(n):02d}</span><div><p class="eyebrow">Раздел {n}</p><h2 id="standard-title-{n}">{html.escape(card["title"])}</h2></div></div>
              <h3>Назначение</h3><p>{h(card["purpose"])}</p>
              <h3>Состав</h3><dl class="v2-composition">{comp}</dl>
              <h3>Как пишем</h3><ul class="v2-list">{how}</ul>
              <h3>Критерии приёмки</h3><table class="v2-criteria"><tbody>{crit}</tbody></table>
              <h3>Метрики</h3><ul class="v2-metrics">{metrics}</ul>
              <details class="standard-detail"><summary>{html.escape(ex_title)}</summary><p>{h(ex_body)}</p></details>
              <p class="standard-sources">Основание: {sources}</p>
            </article>"""


def standards_html() -> str:
    index = "\n".join(
        f'            <a href="#standards?section={c["n"]}" data-standard-target="{c["n"]}"><span>{int(c["n"]):02d}</span> {html.escape(c["title"])}</a>'
        for c in C.CARDS
    )
    cards = "".join(card_html(c) for c in C.CARDS)
    return f"""<section class="page-band standards-band" id="standards" data-page="standards" aria-labelledby="standards-title" hidden>
        <div class="standards-intro">
          <h1 id="standards-title">{html.escape(C.STANDARDS_TITLE)}</h1>
          <p class="standards-lead">{h(C.STANDARDS_LEAD)}</p>
        </div>

        <div class="standards-layout">
          <nav class="standards-index" aria-label="Разделы стандарта BCREQ">
            <a href="#standards?section=0" data-standard-target="0"><span>00</span> Введение</a>
{index}
          </nav>

          <div class="standards-content">
            {intro_html()}
{cards}
          </div>
        </div>
      </section>"""


# ------------------------------------------------------------------ patching
def replace_once(text: str, old: str, new: str, what: str) -> str:
    if text.count(old) != 1:
        raise SystemExit(f"patch '{what}': expected exactly one match, found {text.count(old)}")
    return text.replace(old, new)


def patch_index(src: str) -> str:
    # menu
    nav_start = src.index('        <a href="#catalog" data-nav="catalog">')
    nav_end = src.index('        <button\n          class="icon-button"\n          id="site-logout"')
    src = src[:nav_start] + nav_html() + "\n" + src[nav_end:]
    src = replace_once(src, '<link rel="stylesheet" href="standards.css" />',
                       '<link rel="stylesheet" href="standards.css" />\n    <link rel="stylesheet" href="v2.css" />', "css")
    src = replace_once(src, '<script src="app.js" type="module"></script>',
                       '<script src="app.js" type="module"></script>\n    <script src="v2.js" defer></script>', "js")
    # О проекте before the catalog
    src = replace_once(src, "    <main>\n", "    <main>\n" + about_html(), "about")
    # Standards page
    s_start = src.index('<section class="page-band standards-band" id="standards"')
    s_end = src.index("</section>\n    </main>", s_start) + len("</section>")
    src = src[:s_start] + standards_html() + "\n" + glossary_html() + src[s_end:]
    # Processes: two collapsible streams
    for (sid, stream), eyebrow in zip(C.PROCESS_STREAMS, ("Ручной процесс БА · BCREQ", "Команда и Заказчик · гейты Г-IN, Г-С1, Г-W")):
        start = src.index(f'id="{sid}"')
        open_end = src.index(">", start) + 1
        close = src.index("</section>", open_end)
        head_start = src.index('<div class="section-head">', open_end)
        head_end = src.index("</a>\n        </div>", head_start) + len("</a>\n        </div>")
        head = src[head_start:head_end].replace(
            f'<p class="eyebrow">{eyebrow}</p>', f'<p class="eyebrow">{html.escape(stream)}</p>'
        )
        if stream not in head:
            raise SystemExit(f"patch stream {sid}: eyebrow not found")
        body = src[head_end:close]
        src = (
            src[:open_end]
            + f'\n        <details class="v2-stream" open>\n        <summary class="v2-stream-summary">{head}</summary>'
            + body
            + "        </details>\n      "
            + src[close:]
        )
    return src


APP_JS_PATCHES = [
    (
        'const PAGES = ["catalog", "standards", "dashboard", "roadmap", "processes", "patterns"];',
        'const PAGES = ["about", "catalog", "standards", "dashboard", "roadmap", "processes", "patterns", "glossary"];',
    ),
    (
        "    if (/^[1-8]$/.test(section || \"\")) {\n      const target = document.getElementById(`standard-${section}`);",
        "    if (/^[0-8]$/.test(section || \"\")) {\n      const target = document.getElementById(section === \"0\" ? \"standard-intro\" : `standard-${section}`);",
    ),
]


def build_out() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    shutil.copytree(SITE, OUT)
    index = OUT / "index.html"
    index.write_text(patch_index(index.read_text(encoding="utf-8")), encoding="utf-8")
    app = OUT / "app.js"
    js = app.read_text(encoding="utf-8")
    for old, new in APP_JS_PATCHES:
        js = replace_once(js, old, new, "app.js")
    app.write_text(js, encoding="utf-8")
    shutil.copy(HERE / "v2.css", OUT / "v2.css")
    shutil.copy(HERE / "v2.js", OUT / "v2.js")
    flow = OUT / "data" / "bcreq-flow.json"
    data = flow.read_text(encoding="utf-8")
    for old, new in C.DATA_LABEL_FIXES:
        data = replace_once(data, json.dumps(old, ensure_ascii=False), json.dumps(new, ensure_ascii=False), old)
    flow.write_text(data, encoding="utf-8")


# ------------------------------------------------------------------ Markdown
def pages_md() -> str:
    a = C.ABOUT
    lines = [
        "<!-- Generated by experiments/issue_420/site-v2/build.py from content.py. Do not edit by hand. -->",
        "",
        "### Меню",
        "",
        " · ".join(label for _, label in C.NAV),
        "",
        "### О проекте",
        "",
        f"**{a['title']}.** {md(a['lead'])}",
        "",
        "| Видение | |",
        "| --- | --- |",
    ]
    lines += [f"| {k} | {md(v)} |" for k, v in a["vision"]]
    lines += ["", "Принципы:", ""] + [f"- {md(p)}" for p in a["principles"]]
    lines += ["", f"Мета-модель бизнес-анализа. {md(a['meta_model'])}", ""]
    lines += ["| Этап | Как работает | Статус |", "| --- | --- | --- |"]
    lines += [f"| {n}. {t} | {md(d)} | {st} |" for n, t, d, st in a["stages"]]
    lines += ["", "Разделы сайта:", ""] + [f"- **{name}** — {md(text)}" for name, _, text in a["zones"]]
    lines += ["", "### Стандарты", "", f"# {C.STANDARDS_TITLE}", "", md(C.STANDARDS_LEAD), "", f"## {C.INTRO_TITLE}", ""]
    for n, title, comment, subs in C.INTRO:
        lines.append(f"{n}. **{md(title)}** — {md(comment)}")
        for sn, st, sc in subs:
            lines.append(f"   - {sn} {md(st)}" + (f" — {md(sc)}" if sc else ""))
    for card in C.CARDS:
        lines += ["", f"## {card['n']}. {card['title']}", "", f"**Назначение.** {md(card['purpose'])}", "", "**Состав.**", ""]
        lines += [f"- {md(k)} — {md(v)}" for k, v in card["composition"]]
        lines += ["", "**Как пишем.**", ""] + [f"- {md(x)}" for x in card["how"]]
        lines += ["", "**Критерии приёмки.**", "", "| Пункт | Принимаем, когда |", "| --- | --- |"]
        lines += [f"| {md(k)} | {md(v)} |" for k, v in card["criteria"]]
        lines += ["", "**Метрики.** " + "; ".join(f"{md(k)} — {md(v)}" for k, v in card["metrics"]) + "."]
        lines += ["", f"**{card['example'][0]}** (свёрнуто). {md(card['example'][1])}"]
        lines += ["", "**Основание:** " + " · ".join(f"[{label}]({url})" for label, url in card["sources"])]
    lines += ["", "### Процессы", ""]
    lines += [f"- `<details>` {title} — содержание потока без изменений, кроме подписи «{C.DATA_LABEL_FIXES[0][1]}»." for _, title in C.PROCESS_STREAMS]
    lines += ["", "### Дашборд", "", "Метрики и прогресс этапов без поясняющих абзацев (`.phase-summary` скрыт).", ""]
    lines += ["### Справочник", "", "| Термин | Расшифровка | Определение | Источник |", "| --- | --- | --- | --- |"]
    for gid, gtitle in C.GLOSSARY_GROUPS:
        lines.append(f"| **{gtitle}** | | | |")
        lines += [
            f"| {label} | {full} | {md(definition)} | [{slabel}]({surl}) |"
            for tid, label, full, definition, slabel, surl, group in C.GLOSSARY
            if group == gid
        ]
    return "\n".join(lines) + "\n"


def rfc_with_appendix(rfc_text: str, block: str) -> str:
    if BEGIN not in rfc_text or END not in rfc_text:
        raise SystemExit(f"{RFC.relative_to(ROOT)}: no BEGIN/END markers for the site-v2 appendix")
    start = rfc_text.index(BEGIN) + len(BEGIN)
    end = rfc_text.index(END)
    return rfc_text[:start] + "\n" + block + rfc_text[end:]


def main(argv: list[str]) -> int:
    block = pages_md()
    rfc_text = RFC.read_text(encoding="utf-8")
    expected_rfc = rfc_with_appendix(rfc_text, block)
    if "--check" in argv:
        errors = []
        if not PAGES_MD.exists() or PAGES_MD.read_text(encoding="utf-8") != block:
            errors.append(f"{PAGES_MD.relative_to(ROOT)} is stale: run build.py")
        if rfc_text != expected_rfc:
            errors.append(f"{RFC.relative_to(ROOT)}: appendix is stale: run build.py")
        # The patch must apply to the current site/ (fails loudly if site/ drifted).
        patch_index((SITE / "index.html").read_text(encoding="utf-8"))
        for err in errors:
            print("ERROR:", err)
        print("site-v2 check:", "FAIL" if errors else "OK")
        return 1 if errors else 0
    build_out()
    PAGES_MD.write_text(block, encoding="utf-8")
    RFC.write_text(expected_rfc, encoding="utf-8")
    print(f"built {OUT.relative_to(ROOT)}; wrote {PAGES_MD.relative_to(ROOT)} and the RFC appendix")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
