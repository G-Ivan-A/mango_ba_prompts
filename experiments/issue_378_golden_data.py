def numbered_incidents() -> list[dict]:
    """Вхождения с идентификаторами ``I-001…`` в порядке реплик (устойчивая сортировка)."""
    rows = sorted(INCIDENTS, key=lambda row: row["turn"])
    result = []
    for index, row in enumerate(rows, 1):
        row = {"id": f"I-{index:03d}", **row}
        if row["det_turn"] is not None and row["det_turn"] > row["turn"]:
            # «user» — БА поймал дефект в ближайшей своей реплике, иначе «user-later».
            lag = (row["det_turn"] - row["turn"] + 1) // 2
            row["det"] = "user" if lag == 1 else "user-later"
        elif row["det_turn"] is not None:
            # Повтор уже отклонённого: правило БА дано раньше дефекта.
            row["det"] = "run"
        result.append(row)
    return result
