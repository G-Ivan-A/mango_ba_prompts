def build():
    baseline = json.loads((BASE / 'source-baseline.json').read_text())
    atoms = list(ATOMS)
    for number, description in enumerate(ACCEPTANCE, 1):
        phase = ('0' if number == 1 else '1' if number in (2, 3) else '2' if number == 4
                 else '3' if number in (5, 6) else '4' if number == 7 else '5')
        state = 'gate_0_evidence' if number in (1, 11) else 'pending'
        atoms.append((f'AC{number:02d}', str(188 + number), description, phase, state))
    rows = []
    for key, lines, description, phase, state in atoms:
        rows.append({
            'id': key, 'source_url': URL, 'source_body_lines': lines,
            'source_body_sha256': baseline['issue']['body_sha256'],
            'source_paraphrase': description,
            'decision_status': 'APPROVED',
            'approval_basis': 'Требование явно поставлено Фаундером в исходном issue; не приёмка результата агента.',
            'phase_owner': phase, 'implementation_state': state,
            'methodology_location': None,
            'architecture_and_asset_locations': [],
            'assignment_plan_url': REPORT,
            'verification_method': ('Pinned Git tree comparison and regression tests'
                                    if key in ('S01', 'C12', 'G01', 'G04', 'AC01')
                                    else 'Содержательная проверка по исходному требованию в ответственном этапе'),
            'evidence_urls': [REPORT, TEST] if state == 'gate_0_evidence' else [],
            'actual_result': ('Техническое evidence Gate 0 доступно; приёмка Фаундером не получена.'
                              if state == 'gate_0_evidence' else 'Не завершено.'),
        })
    return {
        'scope': 'Assignment requirements only; domain requirements reconstruction is pending Iteration 1.',
        'lifecycle': ['Founder Intent', 'Requirements', 'Methodology', 'Architecture',
                      'Prompts / Rules / Templates', 'Execution', 'Validation', 'Feedback'],
        'founder_acceptance_records': [],
        'requirements': rows,
    }


if __name__ == '__main__':
    (BASE / 'requirements.json').write_text(json.dumps(build(), ensure_ascii=False, indent=2) + '\n')
