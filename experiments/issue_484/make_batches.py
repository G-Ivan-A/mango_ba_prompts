def main() -> None:
    rows = {r["rid"]: r for r in json.loads((HERE / "atoms.json").read_text(encoding="utf-8"))}
    sim = json.loads((HERE / "atom_similarity.json").read_text(encoding="utf-8"))
    covered = set(HEADINGS)
    for name, (topic, rids) in BATCHES.items():
        lines = [f"# Батч {name}: {topic}", ""]
        for rid in rids:
            row = rows[rid]
            assert rid not in covered, rid
            covered.add(rid)
            # Колонка 2 отчёта — непустые значения колонок «Требования» и (лист SLA)
            # «Максимальный срок решения заявки», склеенные переводом строки.
            full = "\n".join(t for t in (row["text"], row["tail"]) if t)
            lines += [f"### {rid}", f"№: {row['num']}", "",
                      full.replace("\n", "<br>"), "", "Атомарные части:"]
            for i, atom in enumerate(row["atoms"], start=1):
                lines.append(f"[{i}] {atom}")
            hints = []
            for i, atom in enumerate(row["atoms"], start=1):
                best = sim.get(f"{rid}#{i}")
                if best is None:
                    continue
                # Короткие атомы дают шумное сходство — подсказка только для содержательных
                # формулировок либо при срабатывании правила > 90 %.
                if best["max"] > 0.9 or (best["max"] > 0.6 and len(atom) >= 40):
                    item = max(("raw", "core", "dice"), key=lambda m: best[m])
                    hints.append(f"v4: атом {i} ~ п/п {best[item + '_item']} ({best['max']:.3f})")
            if hints:
                lines += ["", *hints]
            lines.append("")
        (RESEARCH / f"{name}_rows.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{name}: {len(rids)} строк")
    missing = set(rows) - covered
    assert not missing, missing
    print(f"всего строк: {len(rows)} (заголовков: {len(HEADINGS)})")


if __name__ == "__main__":
    main()
