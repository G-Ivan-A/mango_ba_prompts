"""BL-167: обязательный блок «Отраслевая практика — на решение БА» (плечо B RUN-0086)."""
RULE = """### Отраслевая практика — на решение БА

Блок обязателен в итоге шага и стоит вне разделов BCREQ. В него идёт
практика, которая прямо относится к объекту этой задачи: до трёх пунктов. У
каждого пункта — проверяемый источник (каталог runtime, названный стандарт
или руководство, существующий API продукта; «обычно так делают» источником
не считается), одна строка «что даст» и отметка «в раздел не включено».
Нет применимой практики с таким источником — напиши «практика не найдена»;
для полноты пункт не добавляется. В текст раздела практика попадает только
после решения БА с записью в 8.5: запрет L-03 и правило АД-1 не меняются.
"""
BLOCK = """Отраслевая практика — на решение БА
| Практика | Источник | Что даст | Статус |
<до 3 строк со статусом «в раздел не включено» или строка «практика не найдена»>

"""
API_RULE = """
Для новых полей и методов добавь в блок строку сверки с существующим API
продукта: совпадают ли имена и структура с тем, что уже есть в источнике, и
где расхождение. API продукта во входе нет — так и напиши; поля не домысливай.
"""
API_BLOCK = """Сверка с API продукта: <новое поле → поле существующего API, локатор | расхождение | «API продукта во входе нет»>

"""
S1 = "prompts/bcreq-context-understanding-stepwise.md"
S3 = "prompts/bcreq-fr-documentation-stepwise.md"
S6 = "prompts/bcreq-orr-solution-design-stepwise.md"
S3_STEP = """5. **Индустриально значимые.** Отдельным блоком «Индустриально значимые — на
   решение БА»: ФТ, источник практики, последствие отказа. В список 3.N — только
   после решения БА.
"""
S3_STEP_NEW = """5. **Отраслевая практика.** ФТ, которое диктует практика, а не запрос, идёт в
   блок «Отраслевая практика — на решение БА»; в «что даст» назови и последствие
   отказа. В список 3.N — только после решения БА.
"""
S3_FMT = """Индустриально значимые — на решение БА
| ФТ | Источник практики | Последствие отказа |

"""


def once(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new)


def apply(path, text):
    head = "## 5. Формат вывода\n"
    if path == S1:
        text = once(text, head, RULE + "\n" + head)
        return once(text, "8.4 Реестр вопросов\n| ID | Вопрос", BLOCK + "8.4 Реестр вопросов\n| ID | Вопрос")
    if path == S3:
        text = once(text, S3_STEP, S3_STEP_NEW)
        text = once(text, head, RULE + "\n" + head)
        return once(text, S3_FMT, BLOCK)
    if path == S6:
        text = once(text, head, RULE + API_RULE + "\n" + head)
        return once(text, "8.2 Зависимости, 8.4 Реестр", BLOCK + API_BLOCK + "8.2 Зависимости, 8.4 Реестр")
    raise ValueError(path)
