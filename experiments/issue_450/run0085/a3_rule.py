"""BL-156г: уточнение правила «правка без добавлений» Ш-В (плечо A3, RUN-0085).

Формулировка — рекомендация 1 отчёта RUN-0084. Меняется ровно одно предложение:
две независимые вещи делятся, шаги одного процесса — нет (L-25).
"""
BEFORE = (
    "  Неатомарное ФТ (два действия или условия в одном пункте) вариант делит\n"
    "  на отдельные ФТ, по одному действию в каждом. Механизм, объект, роль,\n"
)
AFTER = (
    "  Неатомарное ФТ (два независимых действия или условия в одном пункте)\n"
    "  вариант делит на отдельные ФТ. Шаги одного процесса в отдельные ФТ не\n"
    "  дробятся (L-25). Механизм, объект, роль,\n"
)


def apply(text: str) -> str:
    assert text.count(BEFORE) == 1
    return text.replace(BEFORE, AFTER)
