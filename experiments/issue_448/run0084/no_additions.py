"""Правило «правка без добавлений» для Ш-В (BL-156в, issue #448).

Ответ владельца в issue #448, пункт 4: плечо A2 добавляет правило «правка
без добавлений». Источник формулировки — рекомендация 2 отчёта RUN-0082:
правка только удаляет, делит или заменяет на `[ТРЕБУЕТСЯ УТОЧНЕНИЕ]` с
вопросом в 8.4; неатомарное ФТ делится на отдельные ФТ, по одному
действию; механизм, объект или поведение без источника в правку не
вносятся.

Правило — одна строка-пункт в разделе 4 «Правила раздела», сразу после
пункта о варианте как предложении (АД-2). Якорь должен встретиться ровно
один раз, иначе AssertionError.
"""
from __future__ import annotations

ANCHOR = "- Вариант — предложение; решение за автором (АД-2). Не меняй текст документа.\n"

RULE = (
    "- Правка без добавлений. Вариант только удаляет лишнее, делит пункт или\n"
    "  заменяет недоказанное на `[ТРЕБУЕТСЯ УТОЧНЕНИЕ: …]` с вопросом в 8.4.\n"
    "  Неатомарное ФТ (два действия или условия в одном пункте) вариант делит\n"
    "  на отдельные ФТ, по одному действию в каждом. Механизм, объект, роль,\n"
    "  число или поведение, которых нет во входе и в источнике, в вариант не\n"
    "  вносятся, даже если кажутся очевидными (АД-1, АД-6).\n"
)


def apply_rule(text: str) -> str:
    """Вставить правило после якоря; якорь обязан встретиться ровно один раз."""
    assert text.count(ANCHOR) == 1, text.count(ANCHOR)
    assert RULE not in text, "правило уже есть"
    return text.replace(ANCHOR, ANCHOR + RULE)
