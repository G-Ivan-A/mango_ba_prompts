def front(path: Path) -> dict[str, str]:
    data: dict[str, str] = {}
    lines = path.read_text(encoding="utf-8").splitlines()
    for line in lines[1:]:
        if line.strip() == "---":
            break
        key, _, value = line.partition(":")
        if ":" in line and not line.startswith((" ", "-")):
            data[key.strip()] = value.strip().strip('"')
    return data


def kb(doc: str, section_file: str) -> str:
    """Атомарная ссылка `[ДОК, §X «Заголовок», с.Y](url)` по frontmatter раздела."""
    path = KB / DOCS[doc] / "sections" / section_file
    fm = front(path)
    assert fm["doc_code"] == doc, path
    number = fm.get("pdf_section", "")
    if number in ("", "0", "-", "—"):
        number = fm.get("section", "")
    if number in ("", "0", "-", "—"):
        number = ""
    title = fm["title"]
    sect = f"§{number} " if number else ""
    return f"[{doc}, {sect}«{title}», с.{fm['pages']}]({BLOB}{DOCS[doc]}/sections/{section_file})"


def portal(key: str) -> str:
    title, url = PORTAL[key]
    return f"[{title}]({url})"


